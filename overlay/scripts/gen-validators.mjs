// Compile schema validators at build time: renderer validation must not require CSP unsafe-eval.
import Ajv2020 from 'ajv/dist/2020.js'
import standaloneCode from 'ajv/dist/standalone/index.js'
import { readFile, writeFile } from 'node:fs/promises'
const schema = JSON.parse(await readFile(new URL('../../protocol/messages.schema.json', import.meta.url), 'utf8'))
const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true } })
ajv.addSchema(schema)
const exports = { Envelope: `${schema.$id}#/$defs/Envelope` }
for (const type of Object.keys(schema['x-messages'])) exports[`payload_${type}`] = `${schema.$id}#/$defs/payload_${type}`
const source = standaloneCode(ajv, exports).replaceAll('require("ajv/dist/runtime/ucs2length").default', 'ucs2length')
if (source.includes('require(')) throw new Error('Unexpected CommonJS helper in standalone validators')
// Inlined instead of imported: under the Vite dev server, a default import of that CommonJS module
// yields its exports object, not the function, so every minLength check threw ("func1 is not a function").
const ucs2length = `function ucs2length(str) {
  const len = str.length
  let length = 0
  let pos = 0
  while (pos < len) {
    length++
    const value = str.charCodeAt(pos++)
    if (value >= 0xd800 && value <= 0xdbff && pos < len && (str.charCodeAt(pos) & 0xfc00) === 0xdc00) pos++
  }
  return length
}`
await writeFile(new URL('../src/renderer/ws/validators.gen.ts', import.meta.url),
  '// @ts-nocheck\n// GENERATED by scripts/gen-validators.mjs. Do not edit.\n' + source + '\n' + ucs2length + '\n')
console.log('wrote CSP-safe standalone protocol validators')
